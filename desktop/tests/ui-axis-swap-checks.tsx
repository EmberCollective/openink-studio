import React, {act} from 'react';
import {createRoot} from 'react-dom/client';
import assert from 'node:assert/strict';
import App from '../ui/src/App';

export async function run() {
  const events:any[]=[], requests:{name:string,args:any}[]=[];
  const fixture={name:'axis fixture',width_mm:100,height_mm:100,strokes:[[{x:10,y:20},{x:30,y:40}]]};
  (globalThis as any).__openMock=async()=>'/offline/axes.svg';
  (globalThis as any).__invokeMock=async(name:string,args:any)=>{
    requests.push({name,args});
    if(name==='poll_device')return events.splice(0);
    if(name==='import_document')return fixture;
    if(name==='generate_gcode')return '; axis mock';
    if(name==='default_import_options')return {};
    if(name.startsWith('list_'))return [];
    if(name==='optimize_document')return {document:args.document,stroke_order:[0],before_distance_mm:0,after_distance_mm:0,before_travel_seconds:0,after_travel_seconds:0};
    return null;
  };
  const button=(label:string)=>{const node=[...document.querySelectorAll('button')].find(b=>b.textContent?.trim()===label||b.title===label);assert.ok(node,label);return node};
  const click=async(label:string)=>{assert.equal(button(label).disabled,false,label);await act(async()=>button(label).click())};
  const poll=async(...next:any[])=>{events.push(...next);await act(async()=>{await new Promise(resolve=>setTimeout(resolve,240))})};
  const commands=()=>requests.filter(r=>r.name==='device_command');
  const setting=()=>button('X/Y 轴对调');
  window.localStorage.removeItem('openink-swap-xy');
  let root=createRoot(document.getElementById('root')!);
  await act(async()=>root.render(<App/>));
  await click('设置');
  assert.equal(setting().getAttribute('aria-pressed'),'false');
  assert.ok(setting().classList.contains('toggle-row'));
  const before=commands().length;
  await click('X/Y 轴对调');
  assert.equal(commands().length,before,'Changing the setting never sends machine commands');
  assert.equal(window.localStorage.getItem('openink-swap-xy'),'true');
  assert.equal(setting().getAttribute('aria-pressed'),'true');
  setting().focus();assert.equal(document.activeElement,setting());
  await act(async()=>root.unmount());
  root=createRoot(document.getElementById('root')!);await act(async()=>root.render(<App/>));
  await click('设置');assert.equal(setting().getAttribute('aria-pressed'),'true','Setting survives application restart');
  await click('关闭');
  await click('导入素材…');
  await click('预览 CNC / G-code');
  assert.equal(requests.filter(r=>r.name==='generate_gcode').at(-1)!.args.swap_xy,true);
  await click('导出 .gcode');
  assert.equal(requests.filter(r=>r.name==='export_gcode').at(-1)!.args.swap_xy,true);
  await click('关闭');
  await poll({type:'ports',ports:[{name:'MOCK',description:'mock',preferred:true}]});
  await click('设备控制');
  const beforeConnect=commands().length;
  // Both events reach the same render; the synchronous ref must reject the second.
  await act(async()=>{button('连接设备').click();button('连接设备').click()});
  assert.equal(commands().length,beforeConnect+1,'Duplicate same-render connection requests are rejected');
  assert.equal(button('连接设备').disabled,true);
  assert.equal(button('自动识别连接').disabled,true);
  assert.equal((document.querySelector('[aria-label="串口"]') as HTMLSelectElement).disabled,true);
  assert.equal(commands().at(-1)!.args.command.swap_xy,true);
  await click('设置');assert.equal(setting().disabled,true,'Disabled while connecting');await click('关闭');
  await poll({type:'connected',port:'MOCK'},{type:'status',status:{state:'Idle',position:[0,0,0],wco:[0,0,0]}});
  await click('设置');assert.equal(setting().disabled,true,'Mapping is fixed for the connected session');await click('关闭');
  await click('断开连接');await poll({type:'disconnected'});
  await click('设置');assert.equal(setting().disabled,false);await click('关闭');
  await click('连接设备');await poll({type:'error',message:'offline fixture connection failure'});
  await click('清除旧任务并恢复连接');
  assert.deepEqual(commands().at(-1)!.args.command,{type:'recover',port:'MOCK',swap_xy:true});
  await click('设置');assert.equal(setting().disabled,true,'Disabled during recovery');
  await poll({type:'error',message:'offline fixture recovery failure'},{type:'recovering',active:false});
  assert.equal(setting().disabled,false);
  await click('X/Y 轴对调');assert.equal(window.localStorage.getItem('openink-swap-xy'),'false');
  await act(async()=>root.unmount());
  window.localStorage.removeItem('openink-swap-xy');
  console.log('PASS: axis toggle, persistence, no-motion setting, connection/recovery locks and preview/export parity (mock IPC).');
}
