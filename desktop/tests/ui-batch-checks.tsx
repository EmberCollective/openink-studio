import React, { act } from "react";
import { createRoot } from "react-dom/client";
import assert from "node:assert/strict";
import App from "../ui/src/App";

export async function batchChecks() {
  const events: any[] = [], requests: { name: string; args: any }[] = [];
  const fixture = { name: "Batches", width_mm: 160, height_mm: 240, strokes: [10, 40, 70].map(x => [{ x, y: 10 }, { x: x + 10, y: 20 }]) };
  const copy = (v: any) => structuredClone(v);
  (globalThis as any).__openMock = async () => "/offline/batches.svg";
  (globalThis as any).__saveMock = async () => "/offline/batches.inkproj";
  (globalThis as any).__invokeMock = async (name: string, args: any) => {
    requests.push({ name, args: copy(args || {}) });
    if (name === "poll_device") return events.splice(0);
    if (name === "import_document") return copy(fixture);
    if (name === "optimize_document") {
      const stroke_order = args.document.strokes.map((_: any, i: number) => i).reverse();
      return { document: { ...copy(args.document), strokes: stroke_order.map((i: number) => args.document.strokes[i]) }, stroke_order, before_distance_mm: 100, after_distance_mm: 20, before_travel_seconds: 4, after_travel_seconds: .8 };
    }
    if (name === "generate_gcode") return "; mocked code";
    if (name === "default_import_options") return {};
    if (name.startsWith("list_")) return [];
    return null;
  };
  const button = (text: string) => {
    const found = [...document.querySelectorAll("button")].find(node => node.textContent?.trim() === text || node.title === text);
    assert.ok(found, `Missing button ${text}`); return found;
  };
  const click = async (text: string) => { await act(async () => button(text).click()); };
  const poll = async () => { await act(async () => { await new Promise(resolve => setTimeout(resolve, 240)); }); };
  const shapes = () => [...document.querySelectorAll(".canvas-edit-layer polyline")];
  const colors = () => shapes().map(line => line.getAttribute("stroke"));
  const points = () => shapes().map(line => line.getAttribute("points"));
  const assignment = () => document.querySelector<HTMLSelectElement>("#selection-batch")!;
  const assign = async (id: string) => { const node = assignment(); assert.ok(node); await act(async () => { node.value = id; node.dispatchEvent(new Event("change", { bubbles: true })); }); };
  const pointer = async (type: string, x: number, y: number) => { const node = document.querySelector(".canvas-edit-layer.active")!; assert.ok(node); await act(async () => node.dispatchEvent(new MouseEvent(type, { bubbles: true, button: 0, clientX: x * 10, clientY: y * 10 }))); };
  const selectFirst = async () => { await pointer("pointerdown", 2, 2); await pointer("pointermove", 25, 25); await pointer("pointerup", 25, 25); };
  const runs = () => requests.filter(r => r.name === "device_command" && r.args.command.type === "run");
  let root = createRoot(document.getElementById("root")!);
  try {
    await act(async () => root.render(<App />));
    await click("导入素材…");
    const original = points();
    await selectFirst();
    assert.equal(assignment().value, "default");
    await assign("__new");
    const second = assignment().value;
    assert.notEqual(second, "default");
    assert.equal(shapes().length, 3, "Moving to a batch must not duplicate ink");
    assert.deepEqual(points(), original);
    assert.match(document.querySelector(".task-batch-summary")!.textContent!, /2 \/ 2/);
    await click("撤销 Ctrl+Z");
    assert.equal(assignment().value, "default", "Undo restores batch ownership");
    assert.equal(assignment().options.length, 3, "Undo removes newly created batch");
    await click("重做 Ctrl+Shift+Z");
    assert.equal(assignment().value, second);
    await click("全选路径 Ctrl+A");
    assert.equal(assignment().value, "", "Mixed selection shows multiple batches");
    await assign(second);
    assert.equal(assignment().value, second, "Existing batch receives selected mixed content");
    await click("撤销 Ctrl+Z");
    assert.equal(assignment().value, "", "Undo restores mixed ownership");
    await click("线路");
    assert.equal(new Set(colors()).size, 2, "Planning view colors each batch");
    const planningColors = colors();
    assert.equal(planningColors[1], planningColors[2]);
    assert.notEqual(planningColors[0], planningColors[1]);
    await click("属性");
    assert.deepEqual(colors(), planningColors, "Properties retains batch colors while assigning content");
    await click("设备控制");
    assert.deepEqual(colors(), ["#6f55df", "#6f55df", "#6f55df"]);
    await act(async () => document.querySelector<HTMLButtonElement>(".task-batch-summary")!.click());
    assert.ok(document.querySelector('.batch-item[aria-pressed="true"]'), "Task summary opens current batch in planning");
    assert.deepEqual(colors(), planningColors);
    await act(async () => document.querySelectorAll<HTMLButtonElement>(".batch-item")[1].click());
    await poll();
    const route = requests.filter(r => r.name === "optimize_document").at(-1)!;
    assert.equal(route.args.document.strokes.length, 1, "Route planner sees only selected batch");
    assert.equal(route.args.document.strokes[0][0].x, 10);
    events.push({ type: "connected", port: "MOCK" }, { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } });
    await poll();
    await click("预览 CNC / G-code");
    assert.equal(requests.filter(r => r.name === "generate_gcode").at(-1)!.args.job.document.strokes.length, 1);
    await click("关闭");
    await click("开始书写");
    assert.equal(runs().length, 1);
    assert.equal(runs()[0].args.command.job.document.strokes.length, 1);
    assert.equal(runs()[0].args.command.job.document.strokes[0][0].x, 10);
    assert.ok([...document.querySelectorAll<HTMLButtonElement>(".batch-item")].every(b => b.disabled));
    events.push({ type: "job_started" }, { type: "paused", paused: true }); await poll();
    await click("属性");
    assert.equal(assignment().disabled, true, "Paused task locks property batch assignment");
    await click("继续");
    events.push({ type: "paused", paused: false }, { type: "completed" }, { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } }); await poll();
    assert.equal(runs().length, 1, "Completion does not enqueue next batch");
    assert.match(document.querySelector(".task-batch-summary")!.textContent!, /1 \/ 2/);
    assert.equal(shapes().filter(line => line.querySelector("title")?.textContent === "已书写").length, 1);
    await click("开始书写");
    assert.equal(runs().length, 2);
    assert.equal(runs()[1].args.command.job.document.strokes.length, 2);
    assert.deepEqual(runs()[1].args.command.job.document.strokes.map((s: any) => s[0].x).sort(), [40, 70]);
    events.push({ type: "job_started" }, { type: "completed" }, { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } }); await poll();
    assert.equal(button("开始书写").disabled, true);
    assert.deepEqual(points(), original);
    await click("保存工程");
    const saved = requests.filter(r => r.name === "save_project").at(-1)!.args.project.pages[0].document;
    assert.equal(saved.batches.length, 2);
    assert.equal(saved.writtenStrokeIds.length, 3);
    assert.equal(new Set(Object.values(saved.strokeBatches)).size, 2);
    console.log("PASS: property batch assignment/new/mixed/undo, property and planning colors, independent route/code/run, paused lock, completion wait and saved identities (mock IPC).");
  } finally { await act(async () => root.unmount()); }
  root = createRoot(document.getElementById("root")!);
  try {
    requests.length = 0; events.length = 0;
    await act(async () => root.render(<App />));
    await click("导入素材…");
    await selectFirst();
    await assign("__new");
    const interrupted = assignment().value;
    events.push({ type: "connected", port: "MOCK" }, { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } }); await poll();
    await click("开始书写");
    assert.equal(runs().length, 1);
    assert.equal(runs()[0].args.command.job.document.strokes.length, 1);
    events.push({ type: "job_started" }); await poll();
    await click("停止");
    events.push({ type: "stopped" }, { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } }); await poll();
    assert.equal(button("开始书写").disabled, true, "Interrupted batch requires review");
    await assign("__new");
    assert.equal(assignment().value, interrupted, "Direct reassignment cannot bypass interrupted-batch review");
    assert.equal(assignment().options.length, 4, "Rejected reassignment must not create a batch");
    await click("撤销 Ctrl+Z");
    assert.equal(assignment().value, "default", "Undo restores the original batch A");
    assert.equal(assignment().options.length, 3);
    assert.equal(button("开始书写").disabled, true, "Undo must propagate interrupted ink's review requirement from batch B to batch A");
    await click("开始书写");
    assert.equal(runs().length, 1, "No run can bypass review through undo");
    await click("线路");
    assert.ok(document.body.textContent?.includes("本批曾中断"));
    await click("已核对，允许重新开始本批");
    assert.equal(button("开始书写").disabled, false, "Explicit review permits original batch A to run again");
    await click("开始书写");
    assert.equal(runs().length, 2);
    assert.equal(runs()[1].args.command.job.document.strokes.length, 3);
    console.log("PASS: interrupted batch blocks direct reassignment and undo-based review bypass until explicit acknowledgment (mock IPC).");
  } finally { await act(async () => root.unmount()); }
}
export const run = batchChecks;
