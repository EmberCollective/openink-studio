import React, { act } from "react";
import { createRoot } from "react-dom/client";
import assert from "node:assert/strict";
import App from "../ui/src/App";

export async function run() {
  let saved: any, opened: any;
  let templates: any[] = [];
  let rejectScale = false;
  const requests: { name: string; args: any }[] = [];
  const events: any[] = [];
  (globalThis as any).__openMock = async () => "/offline/layout.pdf";
  (globalThis as any).__saveMock = async () => "/offline/layout.inkproj";
  (globalThis as any).__invokeMock = async (name: string, args: any) => {
    requests.push({ name, args: structuredClone(args ?? {}) });
    if (name === "poll_device") return events.splice(0);
    if (name === "device_command" && args.command.type === "set_registration_scale" && rejectScale) throw new Error("模拟比例应用失败");
    if (name === "list_templates") return structuredClone(templates);
    if (name === "save_template") templates.push(structuredClone(args.template));
    if (name === "delete_template") templates = templates.filter(t => t.id !== args.id);
    if (name.startsWith("list_")) return [];
    if (name === "default_import_options") return {};
    if (name === "pdf_background_page") return { data_url: "data:image/png;base64,cGFnZQ==", page: args.page, page_count: 2, width_mm: 180, height_mm: 250 };
    if (name === "save_project") saved = structuredClone(args.project);
    if (name === "open_project") return structuredClone(opened);
    if (name === "optimize_document") return { document: args.document, stroke_order: args.document.strokes.map((_: any, i: number) => i), before_distance_mm: 0, after_distance_mm: 0, before_travel_seconds: 0, after_travel_seconds: 0 };
    return null;
  };
  const button = (name: string) => { const b = [...document.querySelectorAll("button")].find(b => b.textContent?.trim() === name || b.title === name || b.getAttribute("aria-label") === name); assert.ok(b, name); return b; };
  const click = async (name: string) => { const b = button(name); assert.equal(b.disabled, false, name); await act(async () => b.click()); };
  const edit = async (input: HTMLInputElement, value: number) => {
    assert.ok(input); await act(async () => input.focus());
    await act(async () => { Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value")!.set!.call(input, String(value)); input.dispatchEvent(new Event("input", { bubbles: true })); });
    await act(async () => input.blur());
  };
  const field = (label: string) => { const el = [...document.querySelectorAll(".field")].find(el => el.querySelector(".field-label")?.textContent === label); assert.ok(el, label); return el.querySelector<HTMLInputElement>("input")!; };
  const forgets = () => requests.filter(r => r.name === "device_command" && r.args.command.type === "forget_calibration").length;
  const save = async () => { await click("保存工程"); return structuredClone(saved); };
  const reopen = async () => { await click("打开工程"); if (document.querySelector(".project-confirmation")) await click("不保存"); };
  const root = createRoot(document.getElementById("root")!);
  try {
    await act(async () => root.render(<App />)); await click("画板"); await click("导入 PDF 作为背景");
    await save(); assert.equal(saved.pages.length, 2); assert.deepEqual(requests.filter(r => r.name === "pdf_background_page").map(r => r.args.page), [1, 2]);
    assert.ok(saved.pages.every((p: any) => p.document.width_mm === 180 && p.document.height_mm === 250 && !("width_mm" in p.background) && !("height_mm" in p.background)));
    assert.equal(saved.layouts.length, 1); assert.equal(saved.layouts[0].source, "pdf");
    assert.equal(saved.pages[0].layout_id, saved.pages[1].layout_id);
    const calibrated = async (scale: number) => {
      const point = (index: number) => ['X','Y'].map(axis => Number(document.querySelector<HTMLInputElement>(`[aria-label="第${index}点${axis}"]`)!.value));
      const origin = point(1), last = point(document.querySelector('[aria-label="第3点X"]') ? 3 : 2);
      events.push({ type: "connected", port: "MOCK" }, { type: "origin_mode", automatic: false }, { type: "calibration_changed", origin }, { type: "registration_changed", scale, rotation_deg: 0 }, { type: "status", status: { state: "Idle", position: [(last[0]-origin[0])*scale, (origin[1]-last[1])*scale, 0], wco: [0, 0, 0] } });
      await act(async () => { await new Promise(r => setTimeout(r, 240)); });
    };
    await edit(document.querySelector<HTMLInputElement>('[aria-label="第1点X"]')!, 170);
    await edit(document.querySelector<HTMLInputElement>('[aria-label="第1点X"]')!, 180);
    await calibrated(.98);
    assert.equal(document.body.textContent?.includes("用校准数据反推版面"), false);
    await edit(field("横向比例"), 98); await edit(field("纵向比例"), 102);
    await save(); assert.equal(saved.template.width_mm, 180); assert.equal(saved.template.height_mm, 250);
    assert.equal(saved.layouts[0].scale_x, .98); assert.equal(saved.layouts[0].scale_y, 1.02);
    assert.deepEqual(requests.filter(r => r.name === "device_command" && r.args.command.type === "set_registration_scale").at(-1)!.args.command.scales, [.98, 1.02]);
    await edit(field("页边距"), 18); const beforeFlip = forgets(); await click("下一页画板"); await click("上一页画板");
    assert.equal(forgets(), beforeFlip, "Same-group page flips preserve session calibration");
    await save(); assert.equal(saved.layouts[0].margin_mm, 18); assert.equal(saved.template.margin_mm, 18);
    opened = structuredClone(saved); opened.pages[0].document.strokes = [[{ x: 160, y: 20 }, { x: 170, y: 30 }]]; delete opened.pages[0].document.strokeOwners; delete opened.pages[0].document.strokeIds;
    await reopen(); await save(); assert.equal(saved.template.margin_mm, 18, "Opening preserves shared layout styling");
    const sharedRegistration = { scale: 1, rotation_deg: 2, matrix: [.98, -.03, .04, 1.02] };
    events.push({ type: "connected", port: "MOCK" }, { type: "origin_mode", automatic: false }, { type: "calibration_changed", origin: [170, 10] }, { type: "registration_changed", ...sharedRegistration }, { type: "status", status: { state: "Idle", position: [-150, -200, 0], wco: [0, 0, 0] } });
    await act(async () => { await new Promise(r => setTimeout(r, 240)); });
    const beforeAdd = forgets();
    await click("添加页面");
    await act(async () => (document.querySelector(".page-add-options button") as HTMLButtonElement).click());
    const size = document.querySelector<HTMLSelectElement>(".page-popover select")!;
    await act(async () => { size.value = "custom"; size.dispatchEvent(new Event("change", { bubbles: true })); });
    const dimensions = document.querySelectorAll<HTMLInputElement>(".page-popover input[type=number]");
    await edit(dimensions[0], 100); await edit(dimensions[1], 150); await click("添加空白页");
    assert.equal(forgets(), beforeAdd, "Adding a different-sized page preserves the shared work origin");
    const beforeDifferent = forgets(); await click("上一页画板"); await click("下一页画板");
    assert.equal(forgets(), beforeDifferent, "All page groups share the work origin and registration");
    await save(); assert.deepEqual(saved.calibration.origin, [170, 10]); assert.equal(saved.calibration.registration.rotation_deg, 0);
    assert.ok(document.querySelector('[aria-label="本次旋转"]')?.textContent?.includes("+2.000° · 临时"));
    assert.equal(document.querySelector('[data-coordinate="origin-draft"]'), null);
    await click("将当前位置设为工作原点");
    assert.deepEqual(requests.filter(r => r.name === "device_command").at(-1)!.args.command, { type: "confirm_manual_origin", raised_confirmed: true });
    events.push({ type: "calibration_changed", origin: [170, 10] }, { type: "registration_changed", ...sharedRegistration }, { type: "positioning", active: false });
    await act(async () => { await new Promise(r => setTimeout(r, 240)); });
    const beforeScales = await save();
    await edit(field("横向比例"), 90);
    await save();
    const layoutOf = (i: number) => saved.layouts.find((l: any) => l.id === saved.pages[i].layout_id);
    assert.equal(layoutOf(0).scale_x, .98); assert.equal(layoutOf(1).scale_x, .98);
    assert.equal(layoutOf(2).scale_x, .9);
    assert.deepEqual(saved.pages.map((p: any) => [p.document, p.background]), beforeScales.pages.map((p: any) => [p.document, p.background]), "Applying scales never resizes original PDFs or ink");
    rejectScale = true; const rejectedPage = saved.current_page;
    await click("上一页画板"); await save(); assert.equal(saved.current_page, rejectedPage, "Rejected backend scale change must not switch pages");
    rejectScale = false; await click("上一页画板");
    assert.deepEqual(requests.filter(r => r.name === "device_command" && r.args.command.type === "set_registration_scale").at(-1)!.args.command.scales, [.98, 1.02]);
    assert.ok(document.querySelector('[aria-label="本次旋转"]')?.textContent?.includes("+2.000° · 临时"));
    await click("下一页画板");
    const beforeApply = await save(); assert.equal(beforeApply.pages[2].document.width_mm, 100);
    await click("应用到页面…"); await click("清空"); assert.equal(button("应用到 0 页").disabled, true);
    await click("仅未套用"); assert.equal(button("应用到 2 页").disabled, false); await click("全选"); await click("应用到 3 页");
    assert.ok(document.querySelector('[aria-labelledby="layout-pages-title"]'), "Failed preflight leaves selection dialog open");
    assert.ok(document.body.textContent?.includes("第 1 页字迹超出新版面")); await click("关闭");
    assert.deepEqual(await save(), beforeApply, "Out-of-bounds multi-page apply leaves every page and layout unchanged");
    await click("上一页画板"); await click("应用到页面…"); await click("全选"); await click("应用到 3 页");
    assert.equal(document.querySelector('[aria-labelledby="layout-pages-title"]'), null);
    await save();
    assert.ok(saved.layouts.every((l: any) => l.scale_x === .98 && l.scale_y === 1.02), "Unified action applies both scales with the layout");
    assert.ok(document.querySelector('[aria-label="本次旋转"]')?.textContent?.includes("+2.000° · 临时"));
    assert.deepEqual(saved.calibration.origin, [170, 10], "Applying the current layout preserves the session origin");
    assert.equal(document.body.textContent?.includes("应用比例到页面…"), false);
    await edit(field("页边距"), 21); await save();
    assert.equal(new Set(saved.pages.map((p: any) => p.layout_id)).size, 1); assert.equal(saved.layouts.length, 1); assert.equal(saved.layouts[0].margin_mm, 21);
    opened = structuredClone(saved); await reopen(); await click("下一页画板"); await save(); assert.equal(saved.template.margin_mm, 21);
    const beforePhoto = structuredClone(saved);
    await click("导入照片作为背景"); await edit(document.querySelector<HTMLInputElement>('input[aria-label="照片大致宽度"]')!, 190);
    await edit(document.querySelector<HTMLInputElement>('input[aria-label="照片大致高度"]')!, 260); await click("取消背景设置"); await save();
    assert.deepEqual(saved.pages, beforePhoto.pages); assert.deepEqual(saved.layouts, beforePhoto.layouts); assert.deepEqual(saved.template, beforePhoto.template);
    assert.equal(document.querySelector(".left-panel .paper-page-list"), null); assert.equal(document.body.textContent?.includes("新建四角定位页"), false);
    const beforeTemplate = await save();
    await click("模板库"); await click("保存当前版面");
    const templateId = templates[0].id;
    assert.notEqual(templateId, saved.pages[0].layout_id);
    await click("删除选中");
    assert.equal(requests.findLast(r => r.name === "delete_template")?.args.id, templateId);
    assert.equal(templates.length, 0); await click("关闭");
    assert.deepEqual((await save()).layouts, beforeTemplate.layouts, "Deleting a library template preserves the shared layout");
    await click("上一页画板");
    await click("导入 PDF 作为背景");
    const mode = document.querySelector<HTMLSelectElement>('[aria-label="校准方式"]')!;
    await act(async () => { mode.value = 'three'; mode.dispatchEvent(new Event('change', {bubbles:true})); });
    await calibrated(.99); await save();
    assert.equal(saved.template.width_mm, 180);
    const third = saved.calibration.point3;
    assert.equal(document.body.textContent?.includes("尚未建立工作原点"), false);
    const machineCommands = () => requests.filter(r => r.name === "device_command").length;
    const beforeOrigin = machineCommands();
    const originTool = button("设置工作原点");
    assert.ok(originTool.closest('.canvas-edit-tools')); assert.ok(originTool.querySelector('svg')); assert.equal(originTool.textContent?.trim(), '');
    assert.ok(button("将当前位置设为工作原点")); assert.ok(button("重置到画布左上角"));
    await click("设置工作原点");
    const svg = document.querySelector<SVGSVGElement>(".paper > svg")!;
    (svg as any).getScreenCTM = () => ({a:2,b:0,c:0,d:3,e:10,f:20});
    await act(async () => svg.dispatchEvent(new MouseEvent("pointerdown", { bubbles:true,button:0,clientX:70,clientY:140 })));
    const originCommand = requests.filter(r => r.name === "device_command").at(-1)!.args.command;
    assert.deepEqual(originCommand, { type: "calibrate", canvas_x: third[0], canvas_y: third[1], origin_x: 30, origin_y: 40, raised_confirmed: true });
    assert.equal(machineCommands(), beforeOrigin + 1, "Origin tool executes immediately without confirmation");
    console.log("PASS: actual PDF sizes, shared layout edits/save/reopen, automatic origin markers, icon-only toolbar and immediate origin setting (mock IPC).");
  } finally { await act(async () => root.unmount()); }
}
