import React, { act } from "react";
import { createRoot } from "react-dom/client";
import assert from "node:assert/strict";
import App from "../ui/src/App";

export async function registrationChecks() {
  const events: any[] = [], requests: { name: string; args: any }[] = [], profiles: any[] = [];
  const fixture = { name: "Registration fixture", width_mm: 160, height_mm: 240, strokes: [[{ x: 20, y: 20 }, { x: 35, y: 35 }]] };
  const copy = (value: any) => JSON.parse(JSON.stringify(value));
  (globalThis as any).__openMock = async () => "/offline/registration.svg";
  (globalThis as any).__invokeMock = async (name: string, args: any) => {
    requests.push({ name, args: copy(args ?? {}) });
    if (name === "poll_device") return events.splice(0);
    if (name === "list_registration_profiles") return copy(profiles);
    if (name === "save_registration_profile") { profiles.push(copy(args.profile)); return; }
    if (name === "import_document") return copy(fixture);
    if (name === "default_import_options") return {};
    if (["list_fonts", "list_legacy_fonts", "list_glyph_fonts", "list_templates"].includes(name)) return [];
    if (name === "generate_gcode") return "; mocked registered G-code";
    if (name === "optimize_document") return { document: copy(args.document), stroke_order: [0], before_distance_mm: 20, after_distance_mm: 20, before_travel_seconds: 1, after_travel_seconds: 1 };
    return null;
  };
  const button = (text: string) => { const node = [...document.querySelectorAll("button")].find(b => b.textContent?.trim() === text || b.title === text); assert.ok(node, `Missing ${text}`); return node; };
  const click = async (text: string) => { const node = button(text); assert.equal(node.disabled, false, `${text} must be enabled`); await act(async () => node.click()); };
  const poll = async (...next: any[]) => { events.push(...next); await act(async () => { await new Promise(resolve => setTimeout(resolve, 240)); }); };
  const command = (type: string) => requests.filter(r => r.name === "device_command" && r.args.command.type === type);
  const idle = { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } };
  let root = createRoot(document.getElementById("root")!);
  await act(async () => root.render(<App />));
  if (button("画板").getAttribute("aria-pressed") !== "true") await click("画板");
  const details = document.querySelector('.registration-coordinate-details') as HTMLDetailsElement;
  assert.equal(details.open, false, 'Precise point coordinates are collapsed by default');
  const visibility = button('显示校准点');
  assert.equal(visibility.getAttribute('aria-pressed'), 'true');
  assert.ok(visibility.querySelector('.switch.on'), 'Calibration reuses the standard sidebar switch');
  await act(async () => visibility.click());
  assert.equal(document.querySelector('[data-registration-handle]'), null);
  await act(async () => visibility.click());
  const handle = document.querySelector('[data-registration-handle="1"]') as SVGGElement;
  assert.ok(handle, 'Points are editable directly on the canvas even before connection');
  const beforeMotion = requests.filter(r => r.name === 'device_command').length;
  await act(async () => handle.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowRight', bubbles:true})));
  assert.equal((document.querySelector('input[aria-label="第2点X"]') as HTMLInputElement).value, '16', 'Canvas point changes reach the numeric panel');
  assert.equal(requests.filter(r => r.name === 'device_command').length, beforeMotion, 'Changing reference points never moves the machine');
  await act(async () => handle.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowLeft', bubbles:true})));
  await act(async () => (details.querySelector('summary') as HTMLElement).click());
  assert.equal(details.open, true);
  await click("导入素材…");
  await poll({ type: "connected", port: "MOCK" }, idle);
  const scaleField = [...document.querySelectorAll('.field')].find(f => f.querySelector('.field-label')?.textContent === '横向比例')!.querySelector('input')!;
  await act(async () => { scaleField.focus(); Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')!.set!.call(scaleField, '98'); scaleField.dispatchEvent(new Event('input', { bubbles: true })); });
  await act(async () => scaleField.blur());
  assert.equal(button('开始书写').disabled, true, 'Setting page scales before calibration cannot silently use unscaled automatic writing');
  await click("已对齐第一点，确认并移向第二点");
  assert.deepEqual(command('begin_registration').at(-1)!.args.command.preserve_scale, [.98, 1]);
  assert.equal(command("begin_registration").length, 1);
  assert.equal(command("move_to").length, 0, "IPC acceptance alone cannot authorize second-point movement");
  assert.equal(button("开始书写").disabled, true);
  assert.equal(document.querySelector(".canvas-edit-layer.active"), null, "Alignment freezes canvas edits");
  await poll({ type: "positioning", active: true }, { type: "origin_mode", automatic: false }, { type: "calibration_changed", origin: [160, 0] }, { type: "registration_changed", scale: 1, rotation_deg: 0 }, idle);
  assert.equal(command("move_to").length, 0, "Calibration event still waits for positioning completion");
  await poll({ type: "positioning", active: false });
  assert.equal(command("move_to").length, 1);
  assert.equal(command("move_to")[0].args.command.feed, 2500, "Second point uses the current travel speed required by Rust IPC");
  assert.deepEqual(command("move_to")[0].args.command, { type: "move_to", canvas_x: 15, canvas_y: 225, feed: 2500 });
  assert.equal(button("已对齐第二点，完成校准").disabled, true, "Second-point move must complete before confirmation");
  await poll(idle, { type: "positioning", active: false });
  await click("已对齐第二点，完成校准");
  assert.equal(command("finish_registration").length, 1);
  assert.equal(button("开始书写").disabled, true);
  await poll({ type: "calibration_changed", origin: [160, 0] }, { type: "registration_changed", scale: 1.02, rotation_deg: 3 }, idle, { type: "positioning", active: false });
  assert.equal(document.querySelector('[aria-label="校准方案名称"]'), null);
  assert.equal(document.querySelector('[aria-label="已保存校准方案"]'), null);
  assert.equal(profiles.length, 0);
  assert.ok(document.querySelector(".canvas-edit-layer.active"), "Completed registration unlocks editing");
  assert.ok(button("将当前位置设为工作原点")); assert.ok(button("重置到画布左上角"));
  assert.equal(document.body.textContent?.includes("确认归位，仅校准坐标"), false);
  await click("将当前位置设为工作原点");
  assert.deepEqual(command("confirm_manual_origin").at(-1)!.args.command, { type: "confirm_manual_origin", raised_confirmed: true });
  await poll({ type: "calibration_changed", origin: [160, 0] }, { type: "registration_changed", scale: 1.02, rotation_deg: 3 }, idle, { type: "positioning", active: false });
  await click("设备控制");
  assert.equal((document.querySelector('.jog-pad')!.closest('.workspace-tab-content') as HTMLElement).hidden, false);
  await click("书写");
  assert.equal((document.querySelector('input[aria-label="描线速率"]')!.closest('.workspace-tab-content') as HTMLElement).hidden, false);
  if (button("画板").getAttribute("aria-pressed") !== "true") await click("画板");
  await click("预览 CNC / G-code");
  const generated = requests.filter(r => r.name === "generate_gcode").at(-1)!.args;
  assert.deepEqual(generated.registration, { scale: 1.02, rotation_deg: 3 }); assert.deepEqual(generated.origin, [160, 0]);
  await click("导出 .gcode");
  assert.deepEqual(requests.filter(r => r.name === "export_gcode").at(-1)!.args.registration, generated.registration);
  await click("关闭");
  await click("开始书写");
  const run = command("run").at(-1)!.args.command.job;
  assert.equal(run.feed, 1500); assert.equal(run.travel_feed, 2500); assert.deepEqual(run.document.strokes, generated.job.document.strokes);
  await act(async () => root.unmount());

  const beforeRestart = command("apply_registration").length;
  root = createRoot(document.getElementById("root")!); await act(async () => root.render(<App />));
  await poll({ type: "connected", port: "MOCK" }, idle);
  assert.equal(command("apply_registration").length, beforeRestart, "Loading saved profiles never applies stale coordinates");
  assert.equal(document.querySelector('[aria-label="已保存校准方案"]'), null);
  await click("已对齐第一点，确认并移向第二点");
  await poll({ type: "disconnected" });
  assert.equal(document.querySelector('input[aria-label="校准方案名称"]'), null);
  assert.equal(button("已对齐第一点，确认并移向第二点").disabled, true);
  assert.equal(document.querySelector('[role="status"]')?.textContent?.includes("等待设备完成定位"), false);
  await act(async () => root.unmount());
  console.log("PASS: two-point registration event gates, retired profile controls absent, G-code/Run transform and disconnect invalidation (mock IPC).");
}
