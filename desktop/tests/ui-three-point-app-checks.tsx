import React, { act } from "react";
import { createRoot } from "react-dom/client";
import assert from "node:assert/strict";
import App from "../ui/src/App";

export async function run() {
  const events: any[] = [], requests: { name: string; args: any }[] = [];
  let path = "/offline/ink.svg";
  let saved: any;
  (globalThis as any).__saveMock = async () => "/offline/scales.inkproj";
  const ink = { name: "ink", width_mm: 160, height_mm: 240, strokes: [[{ x: 20, y: 30 }, { x: 40, y: 30 }]] };
  const matrix = [1.01, .02, -.01, .99];
  (globalThis as any).__openMock = async () => path;
  (globalThis as any).__invokeMock = async (name: string, args: any) => {
    requests.push({ name, args: structuredClone(args ?? {}) });
    if (name === "poll_device") return events.splice(0);
    if (name === "import_document") return structuredClone(ink);
    if (name === "save_project") saved = structuredClone(args.project);
    if (name === "paper_background") return { path, source_path: path, kind: "image", page: 1, page_count: 1, data_url: "mock:paper", corners: [[0, 0], [1, 0], [1, 1], [0, 1]], guide_lines: args.process ? [{ id: "line-1", start: [10, 30], end: [150, 30] }] : [] };
    if (name === "default_import_options") return {};
    if (name.startsWith("list_")) return [];
    if (name === "optimize_document") return { document: args.document, stroke_order: args.document.strokes.map((_: any, i: number) => i), before_distance_mm: 0, after_distance_mm: 0, before_travel_seconds: 0, after_travel_seconds: 0 };
    return null;
  };
  const commands = () => requests.filter(r => r.name === "device_command").map(r => r.args.command);
  const jogs = () => commands().filter(c => c.type === "jog");
  const button = (name: string) => { const b = [...document.querySelectorAll("button")].find(b => b.textContent?.trim() === name || b.title === name || b.getAttribute("aria-label") === name); assert.ok(b, name); return b; };
  const click = async (name: string) => { assert.equal(button(name).disabled, false, name); await act(async () => button(name).click()); };
  const idle = { type: "status", status: { state: "Idle", position: [0, 0, 0], wco: [0, 0, 0] } };
  const stopped = { type: "positioning", active: false };
  const poll = async (...next: any[]) => { events.push(...next); await act(async () => { await new Promise(resolve => setTimeout(resolve, 240)); }); };
  const select = async (label: string, value: string) => { const el = document.querySelector<HTMLSelectElement>(`select[aria-label="${label}"]`)!; assert.ok(el, label); await act(async () => { el.value = value; el.dispatchEvent(new Event("change", { bubbles: true })); }); };
  const arrow = async (shiftKey: boolean) => { await act(async () => { document.body.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowUp", shiftKey, bubbles: true })); document.body.dispatchEvent(new KeyboardEvent("keyup", { key: "ArrowUp", bubbles: true })); }); };
  const root = createRoot(document.getElementById("root")!);
  try {
    await act(async () => root.render(<App />));
    await click("优化轨迹"); await click("导入素材…");
    await click("画板"); await click("导入照片作为背景"); path = "/offline/photo.png";
    await click("选择照片背景"); await click("下一步"); await act(async () => (globalThis as any).__loadPaperImages()); await click("应用并继续");
    await poll({ type: "connected", port: "MOCK" }, idle);
    await click("确认 1 条并继续"); await select("校准方式", "three");
    await click("已对齐第一点，确认并移向第二点");
    assert.equal(button("设备控制").getAttribute("aria-pressed"), "true", "Starting calibration switches to device controls");
    await poll({ type: "origin_mode", automatic: false }, { type: "calibration_changed", origin: [160, 0] }, { type: "registration_changed", scale: 1, rotation_deg: 0 }, stopped, idle);
    assert.equal(commands().at(-1).type, "move_to");
    await poll(stopped, idle);
    await select("移动步长", "0.5"); await arrow(true); assert.equal(jogs().at(-1).y, 1, "Shift doubles the configured half-millimeter jog");
    const count = jogs().length; await click("线路"); await arrow(false); assert.equal(jogs().length, count, "Positioning tab must not dispatch arrow jogging");
    await click("已对齐第二点，确认并移向第三点");
    assert.equal(commands().at(-1).type, "capture_registration_second");
    const moves = commands().filter(c => c.type === "move_to").length;
    await poll({ type: "registration_changed", scale: 1, rotation_deg: 0, matrix }, stopped, idle);
    assert.equal(commands().filter(c => c.type === "move_to").length, moves, "A matrix event alone does not stand in for second-point capture");
    await poll({ type: "registration_point_captured", index: 2 }, stopped, idle);
    assert.equal(commands().at(-1).type, "move_to");
    assert.equal(button("设备控制").getAttribute("aria-pressed"), "true", "Third-point movement switches back to device controls");
    assert.equal(button("完成并应用").disabled, true); assert.equal(button("开始书写").disabled, true);
    await poll(stopped, idle); if (button("画板").getAttribute("aria-pressed") !== "true") await click("画板"); await click("已对齐第三点，完成校准");
    assert.equal(commands().at(-1).type, "finish_registration_third");
    assert.equal(button("完成并应用").disabled, true, "Accepted finish IPC is not physical completion");
    assert.equal(document.querySelector('[aria-label="校准方案名称"]'), null);
    await poll({ type: "registration_changed", scale: 1, rotation_deg: 0, matrix }, stopped, idle);
    assert.equal(button("完成并应用").disabled, false);
    assert.equal(document.querySelector('[aria-label="校准方案名称"]'), null);
    assert.equal(document.querySelector('[aria-label="已保存校准方案"]'), null);
    assert.equal(requests.some(r => r.name === "save_registration_profile"), false);
    await click("完成并应用"); if (button("画板").getAttribute("aria-pressed") !== "true") await click("画板");
    await click("保存工程");
    const active = saved.layouts.find((l: any) => l.id === saved.pages[saved.current_page].layout_id);
    assert.ok(Math.abs(active.scale_x - Math.hypot(matrix[0], matrix[2])) < 1e-12);
    assert.ok(Math.abs(active.scale_y - Math.hypot(matrix[1], matrix[3])) < 1e-12);
    assert.deepEqual([active.width_mm, active.height_mm], [160, 240]);
    assert.equal(saved.calibration.registration.rotation_deg, 0);
    await select("校准方式", "two");
    await click("已对齐第一点，确认并移向第二点");
    assert.deepEqual(commands().at(-1).preserve_scale, [active.scale_x, active.scale_y], "Later two-point alignment fixes rotation while preserving both saved scales");
    await poll({ type: "calibration_changed", origin: [160, 0] }, { type: "registration_changed", scale: 1, rotation_deg: 0 }, stopped, idle);
    await poll(stopped, idle); if (button("画板").getAttribute("aria-pressed") !== "true") await click("画板"); await click("退出校准");
    assert.equal(commands().at(-1).type, "cancel_registration");
    await poll({ type: "calibration_changed", origin: null }, stopped, idle);
    assert.equal(button("开始书写").disabled, true, "Canceled fixed-origin calibration must block starting a job");
    const generated = requests.filter(r => r.name === "generate_gcode").length;
    await click("预览 CNC / G-code");
    assert.equal(requests.filter(r => r.name === "generate_gcode").length, generated, "Missing fixed origin prevents generation after cancel");
    assert.ok(document.body.textContent?.includes("请先完成纸面定位"));
    console.log("PASS App three-point event gates, automatic device tabs, Shift jogging only in device tab, matrix profile save and canceled-origin G-code guard; all IPC mocked");
  } finally { await act(async () => root.unmount()); }
}
